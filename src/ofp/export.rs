/// A Microsoft Flight Simulator flight plan, the `AceXML`/`SimBase.Document` shape FSX
/// introduced and MSFS 2020/2024 still read.
pub fn pln(d: &Dispatch) -> String {
    let o = &d.route.origin;
    let dest = &d.route.destination;
    let mut s = String::new();
    let _ = writeln!(s, "<?xml version=\"1.0\" encoding=\"UTF-8\"?>");
    let _ = writeln!(s, "<SimBase.Document Type=\"AceXML\" version=\"1,0\">");
    let _ = writeln!(s, "  <Descr>AceXML Document</Descr>");
    let _ = writeln!(s, "  <FlightPlan.FlightPlan>");
    let _ = writeln!(s, "    <Title>{} to {}</Title>", o.icao, dest.icao);
    let _ = writeln!(s, "    <FPType>IFR</FPType>");
    let _ = writeln!(s, "    <RouteType>HighAlt</RouteType>");
    let _ = writeln!(s, "    <CruisingAlt>{:.0}</CruisingAlt>", d.route.cruise_ft);
    let _ = writeln!(s, "    <DepartureID>{}</DepartureID>", o.icao);
    let _ = writeln!(s, "    <DepartureLLA>{}</DepartureLLA>", lla(o.pos.0, o.pos.1, o.elevation_ft * 0.3048));
    let _ = writeln!(s, "    <DestinationID>{}</DestinationID>", dest.icao);
    let _ = writeln!(s, "    <DestinationLLA>{}</DestinationLLA>", lla(dest.pos.0, dest.pos.1, dest.elevation_ft * 0.3048));
    let _ = writeln!(s, "    <Descr>generated by amdbgen</Descr>");
    let _ = writeln!(s, "    <DepartureName>{}</DepartureName>", xml_escape(&o.name));
    let _ = writeln!(s, "    <DestinationName>{}</DestinationName>", xml_escape(&dest.name));
    for w in &d.route.points {
        waypoint_xml(&mut s, w);
    }
    let _ = writeln!(s, "  </FlightPlan.FlightPlan>");
    let _ = writeln!(s, "</SimBase.Document>");
    s
}

fn waypoint_xml(s: &mut String, w: &Waypoint) {
    let _ = writeln!(s, "    <ATCWaypoint id=\"{}\">", xml_escape(&w.ident));
    let _ = writeln!(s, "      <ATCWaypointType>{}</ATCWaypointType>", waypoint_type(w.kind));
    let _ = writeln!(s, "      <WorldPosition>{}</WorldPosition>", lla(w.pos.0, w.pos.1, 0.0));
    if matches!(w.kind, PointKind::Airport) {
        let _ = writeln!(s, "      <ICAO>");
        let _ = writeln!(s, "        <ICAOIdent>{}</ICAOIdent>", xml_escape(&w.ident));
        let _ = writeln!(s, "      </ICAO>");
    }
    let _ = writeln!(s, "    </ATCWaypoint>");
}

pub fn write_pln(d: &Dispatch, out: &Path) -> Result<u64> {
    write_file(out, &pln(d))
}

