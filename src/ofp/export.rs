//! The route in the shapes a simulator's own flight-plan importer reads: the MSFS
//! `.pln`, the X-Plane `.fms` (version 1100), a PMDG-style `.rte`, an ICAO flight plan
//! message (Doc 4444 Appendix 2), and the whole `Dispatch` as JSON.
//!
//! No installed copy of the PMDG 737/777, the FlyByWire or iniBuilds aircraft, or MSFS
//! itself was on the machine this was written on to check a real file against (only the
//! Synaptic A220 was, and it reads SimBrief rather than a route file). The `.pln` and
//! `.fms` writers follow formats that have been the same and openly documented since FSX
//! and X-Plane 10 respectively, which is as close to verified as this machine allows;
//! `.rte` is PMDG's own format and unverified — see the final report.

use crate::dispatch::{Dispatch, PointKind, Waypoint};
use anyhow::{Context, Result};
use std::fmt::Write as _;
use std::path::Path;

fn write_file(out: &Path, contents: &str) -> Result<u64> {
    if let Some(parent) = out.parent() {
        if !parent.as_os_str().is_empty() {
            std::fs::create_dir_all(parent)?;
        }
    }
    std::fs::write(out, contents).with_context(|| format!("write {}", out.display()))?;
    Ok(contents.len() as u64)
}

/// Degrees, minutes and hundredths of a second, the way the `.pln` LLA fields write a
/// coordinate: `N38° 46' 52.68"`.
fn dms(value: f64, pos: char, neg: char) -> String {
    let hemi = if value >= 0.0 { pos } else { neg };
    let a = value.abs();
    let deg = a.floor();
    let min_f = (a - deg) * 60.0;
    let min = min_f.floor();
    let sec = (min_f - min) * 60.0;
    format!("{hemi}{deg:.0}° {min:.0}' {sec:.2}\"")
}

fn lla(lat: f64, lon: f64, alt_m: f64) -> String {
    format!("{},{},{:+011.2}", dms(lat, 'N', 'S'), dms(lon, 'E', 'W'), alt_m)
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('"', "&quot;")
}

fn waypoint_type(kind: PointKind) -> &'static str {
    match kind {
        PointKind::Airport => "Airport",
        PointKind::Sid | PointKind::Star | PointKind::Approach => "Intersection",
        PointKind::Enroute | PointKind::Track => "Intersection",
    }
}

